// Operators (Binary and Uniary)
// 1. Arithmatic Operators (+ - * / % - ++ --)
let num1 = 17;
let num2 = 5;

let ans = num1 + num2;

console.log(ans);
// document.write(ans);
// alert(ans);

// sting concatination method
console.log("The answer is " + ans);

console.log(num1 + " + " + num2 + " = " + ans);

// template literal method
console.log(`The answer is ${ans}`);

console.log(`${num1} + ${num2} = ${ans}`);

ans = num1 - num2;
console.log(`${num1} - ${num2} = ${ans}`);

console.log(`${num1} X ${num2} = ${num1 * num2}`);

console.log(`${num1} / ${num2} = ${num1 / num2}`);

console.log(`${num1} % ${num2} = ${num1 % num2}`);

